"""Local restart checkpoints for long paper runs; final output remains one NPZ.

Checkpoint files are generated by this runner and contain Python simulation
state, so only load checkpoints produced in your own trusted run directory.
"""

from pathlib import Path
import os, signal
import numpy as np
import torch


class Restart:
    def __init__(self, output, recorder, kernel=None):
        self.path = Path(output) / "checkpoint.pt"
        self.recorder = recorder
        self.kernel = kernel
        self.offset = 0
        self.resumed = False
        self._last_saved = -1

        def stop(signum, frame):
            raise SystemExit(128 + signum)

        signal.signal(signal.SIGTERM, stop)
        signal.signal(signal.SIGUSR1, stop)

    def load(self, initial_state, *, bias=None):
        if not self.path.exists():
            return initial_state
        # This file is a local, trusted runner artifact, never a downloaded checkpoint.
        target_device = (
            initial_state.device
            if hasattr(initial_state, "device")
            else initial_state.coordinate.device
        )
        # Generator byte states must stay on CPU while unpickling. Mapping the
        # whole checkpoint to CUDA also moves those byte tensors and breaks
        # torch.Generator.__setstate__.
        saved = torch.load(self.path, map_location="cpu", weights_only=False)
        state = saved["state"]
        if hasattr(state, "to"):
            state = state.to(device=target_device)
        else:
            state.coordinate = state.coordinate.to(target_device)
            state.momentum = state.momentum.to(target_device)
            if state.generator is not None:
                generator = torch.Generator(device=target_device)
                generator.set_state(state.generator.get_state().cpu())
                state.generator = generator
        self.offset = int(saved["step"])
        self.resumed = True
        self.recorder.rows = saved["rows"]
        self.recorder.last_coordinates = saved["last_coordinates"]
        if self.kernel is not None:
            self.kernel.bandwidth = saved["bandwidth"].to(self.kernel.bandwidth)
        if bias is not None:
            n = int(saved["hills_count"])
            bias._ensure_capacity(n)
            bias._centers[:n] = saved["hills_centers"].to(bias._centers)
            bias._heights[:n] = saved["hills_heights"].to(bias._heights)
            bias.n_hills = n
            bias._rebuild_grid_from_hills()
        torch.set_rng_state(saved["cpu_rng"].cpu())
        if torch.cuda.is_available():
            torch.cuda.set_rng_state_all([v.cpu() for v in saved["cuda_rng"]])
        np.random.set_state(saved["numpy_rng"])
        print(
            f"[resume] restored complete state at production step {self.offset}",
            flush=True,
        )
        return state

    def save(self, step, state, *, bias=None):
        if step % 1000 or step == self._last_saved:
            return
        self._last_saved = step
        values = dict(
            step=int(step),
            state=state,
            rows=self.recorder.rows,
            last_coordinates=self.recorder.last_coordinates,
            bandwidth=self.kernel.bandwidth.detach()
            if self.kernel is not None
            else None,
            cpu_rng=torch.get_rng_state(),
            cuda_rng=torch.cuda.get_rng_state_all()
            if torch.cuda.is_available()
            else [],
            numpy_rng=np.random.get_state(),
        )
        if bias is not None:
            values.update(
                hills_count=bias.n_hills,
                hills_centers=bias._centers[: bias.n_hills].detach(),
                hills_heights=bias._heights[: bias.n_hills].detach(),
            )
        temporary = self.path.with_suffix(".tmp")
        torch.save(values, temporary)
        temporary.replace(self.path)
        print(f"[checkpoint] production step {step}", flush=True)

    def finish(self):
        self.path.unlink(missing_ok=True)
